import puppeteer from 'puppeteer-core';
const BASE = process.env.BASE || 'http://localhost:4173/';
const OUT = '/workspace/shortdrama/screenshots/';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage();
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('requestfailed', r => errs.push('fail ' + r.url()));
const wait = (ms) => new Promise(r => setTimeout(r, ms));
const go = async (h, ms = 1500) => { await p.goto(BASE + h, { waitUntil: 'networkidle0' }); await wait(ms); };
const shot = async (n, full = false) => { await p.screenshot({ path: OUT + n + '.png', fullPage: full }); console.log('shot', n); };
await go('#/'); await shot('01-home'); await shot('01b-home-full', true);
await go('#/serie/esposa-del-mar'); await shot('02-serie'); await shot('02b-serie-full', true);
await go('#/serie/loba-rechazada'); await shot('02c-serie-loba-full', true);
await go('#/ver/esposa-del-mar/1', 7000); await shot('03-player');
await go('#/ver/repartidor-heredero/2', 12000); await shot('03b-player-dialogo');
await go('#/ver/cien-dias/10', 1500); await shot('04-paywall');
await go('#/feed', 3000); await shot('05-feed');
await go('#/dashboard', 2500); await shot('06-dashboard'); await shot('06b-dashboard-full', true);
await go('#/guiones'); await shot('07-guiones');
await go('#/guiones/renaci/ep01'); await shot('07b-guion');
await go('#/perfil'); await shot('08-perfil');
await go('#/admin'); await shot('09-admin');
console.log('errors', errs);
await b.close();
